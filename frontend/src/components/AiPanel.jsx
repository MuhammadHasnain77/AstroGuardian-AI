import { Bot, Loader2, Send, Sparkles } from "lucide-react";
import { useEffect, useRef, useState } from "react";
import { api } from "../api.js";

export default function AiPanel({ astronautId, llm, refreshKey }) {
  const [explanation, setExplanation] = useState(null);
  const [loading, setLoading] = useState(false);
  const storeKey = `ag-chat-${astronautId}`;
  const [messages, setMessages] = useState(() => loadChat(storeKey));
  const [question, setQuestion] = useState("");
  const [asking, setAsking] = useState(false);
  const [error, setError] = useState(null);
  const endRef = useRef(null);

  // A new reading changes the evaluation, so drop the old explanation (chat history is kept).
  useEffect(() => {
    setExplanation(null);
    setError(null);
  }, [astronautId, refreshKey]);

  useEffect(() => {
    saveChat(storeKey, messages);
  }, [storeKey, messages]);

  useEffect(() => {
    endRef.current?.scrollIntoView({ block: "nearest" });
  }, [messages]);

  async function explain() {
    setLoading(true);
    setError(null);
    try {
      setExplanation(await api.explain(astronautId));
    } catch (e) {
      setError(e.message);
    } finally {
      setLoading(false);
    }
  }

  async function ask(e) {
    e.preventDefault();
    const q = question.trim();
    if (!q || asking) return;
    const history = messages.map(({ role, content }) => ({ role, content }));
    setMessages((m) => [...m, { role: "user", content: q }]);
    setQuestion("");
    setAsking(true);
    try {
      const r = await api.chat(astronautId, q, history);
      setMessages((m) => [...m, { role: "assistant", content: r.text, source: r.source }]);
    } catch (err) {
      setMessages((m) => [...m, { role: "assistant", content: `Error: ${err.message}`, source: "error" }]);
    } finally {
      setAsking(false);
    }
  }

  return (
    <section className="rounded-xl bg-surface-1 p-5 ring-1 ring-line">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <h2 className="flex items-center gap-2 text-lg font-semibold">
          <Bot className="h-5 w-5 text-series" aria-hidden /> AI health assistant
        </h2>
        <span className="text-xs text-ink-3">
          {llm?.enabled ? `${llm.model} · ${llm.demo_mode ? "demo via Groq API" : "onboard"}` : "LLM offline · template mode"}
        </span>
      </div>
      <p className="mt-1 text-sm text-ink-3">
        Explains the engine's result in plain language. It cannot change the alert level.
      </p>

      <div className="mt-4">
        {!explanation ? (
          <button onClick={explain} disabled={loading}
                  className="inline-flex items-center gap-2 rounded-lg bg-series px-4 py-2 font-medium text-white hover:brightness-110 disabled:opacity-60">
            {loading ? <Loader2 className="h-4 w-4 animate-spin" /> : <Sparkles className="h-4 w-4" />}
            Explain my status
          </button>
        ) : (
          <div className="rounded-lg bg-surface-2 p-4">
            <p className="whitespace-pre-line leading-relaxed text-ink-1">{explanation.text}</p>
            <p className="mt-2 text-xs text-ink-3">
              {explanation.source === "llm" ? `Generated by ${explanation.model}` : "Template explanation (LLM unavailable)"}
            </p>
          </div>
        )}
        {error && <p className="mt-2 text-sm text-status-critical">{error}</p>}
      </div>

      <div className="mt-5 border-t border-line pt-4">
        {messages.length > 0 && (
          <div className="mb-2 flex justify-end">
            <button onClick={() => setMessages([])} className="text-xs text-ink-3 hover:text-ink-1">Clear conversation</button>
          </div>
        )}
        {messages.length > 0 && (
          <ul className="mb-3 max-h-72 space-y-2 overflow-y-auto pr-1">
            {messages.map((m, i) => (
              <li key={i} className={`rounded-lg px-3 py-2 ${m.role === "user" ? "ml-8 bg-series/20" : "mr-8 bg-surface-2"}`}>
                <p className="whitespace-pre-line text-sm leading-relaxed">{m.content}</p>
              </li>
            ))}
            {asking && (
              <li className="mr-8 flex items-center gap-2 rounded-lg bg-surface-2 px-3 py-2 text-sm text-ink-3">
                <Loader2 className="h-4 w-4 animate-spin" /> Thinking…
              </li>
            )}
            <li ref={endRef} />
          </ul>
        )}
        <form onSubmit={ask} className="flex gap-2">
          <label htmlFor="ask" className="sr-only">Ask the assistant</label>
          <input id="ask" value={question} onChange={(e) => setQuestion(e.target.value)} maxLength={2000}
                 placeholder="Ask, e.g. “Why is my heart rate flagged?”"
                 className="min-w-0 flex-1 rounded-lg bg-surface-2 px-3 py-2 text-ink-1 placeholder:text-ink-3 ring-1 ring-line focus:outline-none focus:ring-series" />
          <button type="submit" disabled={asking || !question.trim()} aria-label="Send"
                  className="rounded-lg bg-surface-3 px-3 text-ink-1 hover:bg-line disabled:opacity-50">
            <Send className="h-4 w-4" />
          </button>
        </form>
      </div>
    </section>
  );
}

// Conversation is kept per astronaut in this browser only (a per-viewer convenience).
function loadChat(key) {
  try {
    const v = JSON.parse(localStorage.getItem(key) ?? "[]");
    return Array.isArray(v) ? v.slice(-20) : [];
  } catch {
    return [];
  }
}

function saveChat(key, messages) {
  try {
    localStorage.setItem(key, JSON.stringify(messages.slice(-20)));
  } catch { /* storage unavailable: chat just isn't remembered */ }
}
